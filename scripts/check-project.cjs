const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..')
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/manifest.json'), 'utf8'))
const src = fs.readFileSync(path.join(root,'src/pages/index/index.ux'),'utf8')
const words = fs.readFileSync(path.join(root,'data/words.tsv'),'utf8')
const phrases = fs.readFileSync(path.join(root,'data/phrases.tsv'),'utf8')
const count = s => s.split(/\r?\n/).filter(l => l.trim() && !l.trim().startsWith('#')).length
assert.equal(count(words),350)
assert.equal(count(phrases),150)
assert.equal(manifest.config.designWidth,336)
assert.equal(manifest.router.entry,'pages/index')
assert.deepEqual(manifest.features.map(v=>v.name).sort(),['system.app','system.storage'])
assert.ok(fs.statSync(path.join(root,'src/common/logo.png')).size > 200)
const required = ['onBackPress','exitGame()','app.terminate()','saveProgress()','storage.set','storage.get','recordAnswer','showStats','chooseGroup','flipCard','scroll-y="true"','@click="answerYes"','@click="answerNo"']
for (const field of required) assert.ok(src.includes(field),'Missing '+field)
assert.ok(!src.includes('system.fetch') && !src.includes('system.interconnect'),'This version must remain offline')
console.log('✓ Manifest, 336x480 UI, storage, exit, 350 + 150 TSV cards validated')
